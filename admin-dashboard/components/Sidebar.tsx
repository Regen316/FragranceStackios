'use client';

import Link from 'next/link';
import { useRouter } from 'next/navigation';
import { createBrowserSupabaseClient } from '@/lib/supabase';

interface SidebarProps {
  activePage: string;
}

const navigation = [
  { name: 'Dashboard', href: '/', icon: DashboardIcon },
  { name: 'Users', href: '/users', icon: UsersIcon },
  { name: 'Costs', href: '/costs', icon: CostsIcon },
  { name: 'Fragrances', href: '/fragrances', icon: FragrancesIcon },
  { name: 'Settings', href: '/settings', icon: SettingsIcon },
];

export default function Sidebar({ activePage }: SidebarProps) {
  const router = useRouter();

  async function handleSignOut() {
    const supabase = createBrowserSupabaseClient();
    await supabase.auth.signOut();
    router.push('/login');
  }

  return (
    <div className="flex flex-col w-64 bg-white border-r border-gray-200 min-h-screen">
      {/* Logo */}
      <div className="flex items-center h-16 px-4 border-b border-gray-200">
        <span className="text-xl font-bold text-amber-600">FragranceStack</span>
        <span className="ml-2 text-xs bg-gray-100 text-gray-600 px-2 py-0.5 rounded">Admin</span>
      </div>

      {/* Navigation */}
      <nav className="flex-1 px-2 py-4 space-y-1">
        {navigation.map((item) => {
          const isActive = activePage === item.name.toLowerCase();
          return (
            <Link
              key={item.name}
              href={item.href}
              className={`nav-link ${isActive ? 'active' : ''}`}
            >
              <item.icon className="mr-3 h-5 w-5" />
              {item.name}
            </Link>
          );
        })}
      </nav>

      {/* Sign out */}
      <div className="p-4 border-t border-gray-200">
        <button
          onClick={handleSignOut}
          className="flex items-center w-full px-4 py-2 text-sm text-gray-600 hover:bg-gray-50 rounded-md"
        >
          <LogoutIcon className="mr-3 h-5 w-5" />
          Sign out
        </button>
      </div>
    </div>
  );
}

